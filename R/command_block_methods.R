#' @describeIn apply_command
#'
#' @export
apply_command.cmd_rec <- function(cdb, mapping, x, y, varlab, vs0, vs, vs2, vallabs, ...) {
  if (is.na(varlab)) {
    varlab <- attr(mapping$dat_mod[[y]], "label", exact = TRUE)
  }

  if (is.na(x)) {
    x <- y
  }

  lb <- vs0
  vs <- vs
  ub <- vs2

  recode_df <-
    tibble::tibble(lb, ub = dplyr::coalesce(ub, lb), vs, vallabs) %>%
    dplyr::mutate(
      expr_str = paste0("(", y, " >= ", lb, " & ", y, " <= ", ub, ")")
    ) %>%
    dplyr::group_by(vs) %>%
    dplyr::summarise(
      expr_str = paste(.data$expr_str, collapse = " | "),
      vallabs = vallabs[1]
    )
  cond_statements <-
    recode_df %>%
    dplyr::select(vs, .data$expr_str) %>%
    purrr::pmap(
      function(vs, expr_str) rlang::quo(!!rlang::parse_expr(expr_str) ~ !!vs)
    )

  res_num <- rlang::expr(dplyr::case_when(!!!cond_statements)) %>% eval_in_data(mapping)
  if (x == y) {
    res_num <- dplyr::coalesce(res_num, mapping$dat_mod[[y]])
  }

  mapping$dat_mod[[x]] <- haven::labelled(
    res_num,
    labels = purrr::set_names(recode_df$vs, recode_df$vallabs),
    label = varlab
  )

}

#' @describeIn apply_command
#'
#' @export
apply_command.cmd_sumvar <- function(cdb, mapping, x, y, varlab, vs0, vs, vallabs, ...) {
  if (is.na(varlab)) {
    varlab <- attr(mapping$dat_mod[[y]], "label", exact = TRUE)
  }

  sum_var_vals_n_labs <- tibble::tibble(vs0, vs, vallabs) %>%
    dplyr::group_by(vs) %>%
    dplyr::summarise(
      val_lists = list(vs0),
      val_labs = dplyr::first(vallabs)
    )
  cond_statements <- purrr::map2(
    sum_var_vals_n_labs$val_lists,
    sum_var_vals_n_labs$vs,
    ~ rlang::expr(!!rlang::sym(y) %in% !!.x ~ !!.y)
  )

  vec_num <- rlang::expr(dplyr::case_when(!!!cond_statements)) %>% eval_in_data(mapping)

  mapping$dat_mod[[x]] <- haven::labelled(
    vec_num,
    labels = sum_var_vals_n_labs[-2] %>% dplyr::select(2, 1) %>% tibble::deframe(),
    label = varlab
  )


}

#' @describeIn apply_command
#'
#' @export
apply_command.cmd_dic <- function(cdb, mapping, x, y, ...) {
  vec <- mapping$dat_mod[[y]]

  varlab <- attr(vec, "label", exact = TRUE)
  vallabs <- attr(vec, "labels", exact = TRUE)

  if (!x %in% names(mapping$dat_mod)) {
    mapping$dat_mod[[x]] <- NA_real_
  }

  mapping$dat_mod[[x]] <- haven::labelled(
    mapping$dat_mod[[x]],
    labels = vallabs,
    label = varlab
  )

}

#' @describeIn apply_command
#'
#' @export
apply_command.cmd_autorec <- function(cdb, mapping, x, ...) {
  vec <- mapping$dat_mod[[x]]
  x_labelled <- labelled::to_labelled(as.factor(vec))
  labelled::var_label(x_labelled) <- attr(vec, "label", exact = TRUE)

  mapping$dat_mod[[x]] <- x_labelled

}

