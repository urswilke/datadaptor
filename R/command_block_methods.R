#' @describeIn apply_command
#'
#' @export
apply_command.cmd_add_labs <- function(cdb, mapping, x, varlab = NULL, vs, vallabs, ...) {
  vec <- mapping$dat_mod[[x]]
  old_vallab_vec <- attr(vec, "labels")
  added_vallab_vec <- purrr::set_names(vs, vallabs)
  new_vallab_vec <- merge_vallabs(old_vallab_vec, added_vallab_vec)

  if (is.null(varlab)) {
    varlab <- attr(vec, "label", exact = TRUE)
  } else {
    varlab <- varlab
  }

  mapping$dat_mod[[x]] <- haven::labelled(
    vec,
    labels = new_vallab_vec,
    label = varlab
  )
}

